t = (10, 20, 30, 20)

len(t)          # Returns total number of elements.
max(t)          # Returns the largest element.
min(t)          # Returns the smallest element.
sum(t)          # Returns the total of all numbers.
sorted(t)       # Returns a sorted list from the tuple.
t.count(20)     # Counts occurrences of an element.
t.index(30)     # Returns first index of an element.
10 in t         # Checks if element exists.
50 not in t     # Checks if element does not exist.
tuple([1,2,3])  # Converts list into tuple.
list(t)         # Converts tuple into list.